/**
 * Traduce una clave con notación de punto ('cta.solicitar') al locale dado.
 * Si falta la traducción, cae al español y, en último caso, devuelve la clave.
 */
export function translate(locale, key) {
  const pick = (dict) => key.split('.').reduce((o, k) => (o == null ? o : o[k]), dict);
  const val = pick(UI[locale]);
  if (val != null) return val;
  const es = pick(UI[DEFAULT_LOCALE]);
  return es != null ? es : key;
}
